import Book from "../models/Book.js";

const kajomaGhatDescription = `महेश भारती का पहला उपन्यास "कजोमा घाट" गाँव की सामाजिक पृष्ठभूमि में रची गई एक जीवंत और विचारोत्तेजक कथा है। प्रेम इसकी धुरी है, लेकिन कहानी केवल प्रेम तक सीमित नहीं रहती। यह सामंती व्यवस्था, औपनिवेशिक लूट, नील की खेती, महामारी, शोषण और ग्रामीण जीवन की जटिलताओं को संवेदनशीलता से सामने लाती है।

उपन्यास में जमींदार, रैयत, कामगार, लोहार, बढ़ई, पसारी और गाँव के अन्य पात्र अपने पूरे जीवन-संघर्ष के साथ उपस्थित हैं। कथा दिखाती है कि कठिन परिस्थितियों में प्रेम, एकता और सामूहिक चेतना किस तरह अन्याय के विरुद्ध शक्ति बन सकते हैं। स्त्री संवेदना, सामाजिक समरसता और जनपक्षधर दृष्टि इस उपन्यास को खास बनाती है।

ग्रामीण समाज, इतिहास और प्रगतिशील हिंदी साहित्य में रुचि रखने वाले पाठकों के लिए "कजोमा घाट" एक पठनीय और प्रभावशाली उपन्यास है।`;

export async function syncCatalogContent() {
  const result = await Book.updateOne(
    { title: /^कजोमा\s+घाट$/u, rating: { $exists: false } },
    { $set: { description: kajomaGhatDescription, rating: 5 } }
  );
  if (result.matchedCount) console.log("Synced catalog content for कजोमा घाट");
}
